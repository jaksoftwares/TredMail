#!/usr/bin/env bash
# ==============================================================================
# TredMail Automated Production Deployment Script for Hostinger KVM VPS
# A Product of Dovepeak Technology
# ==============================================================================

set -e

echo "🚀 Starting TredMail Production Deployment on Hostinger KVM..."

# 1. Update OS packages
echo "📦 Updating Ubuntu package repositories..."
sudo apt-get update -y && sudo apt-get upgrade -y
sudo apt-get install -y curl git ufw jq dnsutils

# 2. Install Docker & Docker Compose if not present
if ! command -v docker &> /dev/null; then
    echo "🐳 Installing Docker Engine..."
    curl -fsSL https://get.docker.com -o get-docker.sh
    sudo sh get-docker.sh
    sudo usermod -aG docker $USER
    rm get-docker.sh
fi

if ! docker compose version &> /dev/null; then
    echo "🐳 Installing Docker Compose Plugin..."
    sudo apt-get install -y docker-compose-plugin
fi

# 3. Deliverability Diagnostic: Check Reverse DNS (PTR)
SERVER_IP=$(curl -s -4 https://ifconfig.me || hostname -I | awk '{print $1}')
echo "🔍 Checking Reverse DNS for IP: $SERVER_IP..."
PTR_RECORD=$(dig -x $SERVER_IP +short || true)

if [ -z "$PTR_RECORD" ]; then
    echo "⚠️ WARNING: No PTR (Reverse DNS) record detected for $SERVER_IP."
    echo "   Action needed: Go to Hostinger hPanel -> VPS -> Settings -> IP address -> Set PTR to mail.tredmail.dovepeak.com"
else
    echo "✅ Reverse DNS detected: $PTR_RECORD"
fi

# 4. Deliverability Diagnostic: Check Outbound Port 25
echo "🔍 Checking Outbound Port 25 Connectivity..."
if timeout 5 bash -c '</dev/tcp/gmail-smtp-in.l.google.com/25' 2>/dev/null; then
    echo "✅ Port 25 Outbound is OPEN and reachable."
else
    echo "⚠️ NOTICE: Outbound Port 25 connection timed out."
    echo "   If blocked, contact Hostinger support to unblock port 25 for your business transactional emails."
fi

# 5. Environment file. STAGE=staging deploys a staging stack whose outbound mail is captured
#    by Mailpit instead of delivered.
STAGE="${STAGE:-production}"
ENV_FILE=".env"
[ "$STAGE" = "staging" ] && ENV_FILE=".env.staging"
COMPOSE=(docker compose -f docker-compose.prod.yml --env-file "$ENV_FILE" -p "tredmail-$STAGE")
[ "$STAGE" = "staging" ] && COMPOSE+=(--profile staging-relay)

if [ ! -f "$ENV_FILE" ]; then
    : "${CONSOLE_DOMAIN:?Set CONSOLE_DOMAIN, API_DOMAIN and TRACKING_DOMAIN before the first deploy}"
    : "${API_DOMAIN:?Set API_DOMAIN}"
    : "${TRACKING_DOMAIN:?Set TRACKING_DOMAIN}"
    echo "📝 Generating $ENV_FILE with fresh secrets..."
    umask 077
    {
        echo "# Generated by deploy-hostinger.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Back this file up securely:"
        echo "# losing TREDMAIL_MASTER_ENCRYPTION_KEY makes every stored DKIM key unrecoverable."
        echo "CONSOLE_DOMAIN=$CONSOLE_DOMAIN"
        echo "API_DOMAIN=$API_DOMAIN"
        echo "TRACKING_DOMAIN=$TRACKING_DOMAIN"
        echo "PRIMARY_DOMAIN=${PRIMARY_DOMAIN:-tredmail.dovepeak.com}"
        echo "TREDMAIL_MASTER_ENCRYPTION_KEY=$(openssl rand -hex 32)"
        echo "INTERNAL_API_TOKEN=$(openssl rand -hex 32)"
        echo "BETTER_AUTH_SECRET=$(openssl rand -hex 32)"
        echo "POSTGRES_PASSWORD=$(openssl rand -hex 24)"
        if [ "$STAGE" = "staging" ]; then
            echo "SMTP_HOST=mailpit"
            echo "SMTP_PORT=1025"
        else
            echo "# Point at the MTA (roadmap Phase 2). Production cannot deliver mail until this is set."
            echo "SMTP_HOST=${SMTP_HOST:-}"
            echo "SMTP_PORT=${SMTP_PORT:-25}"
        fi
    } > "$ENV_FILE"
    echo "🔑 Generated encryption key, internal token, session secret and database password."
fi

# 6. Build images, start the database, apply migrations, then start everything
echo "🚢 Building and starting TredMail ($STAGE)..."
"${COMPOSE[@]}" build
"${COMPOSE[@]}" up -d postgres redis
echo "🗄️ Applying database migrations..."
"${COMPOSE[@]}" run --rm --no-deps api npx prisma migrate deploy --schema=packages/db/prisma/schema.prisma
"${COMPOSE[@]}" up -d

# 7. Seed the platform and Dovepeak workspaces (prints an owner password and an API key once)
echo "🌱 Seeding workspaces..."
"${COMPOSE[@]}" run --rm --no-deps api node apps/api/dist/cli/seed.js

# shellcheck disable=SC1090
source <(grep -E '^(CONSOLE|API|TRACKING)_DOMAIN=' "$ENV_FILE")
echo ""
echo "=============================================================================="
echo "🎉 TredMail ($STAGE) is up"
echo "   Console:  https://$CONSOLE_DOMAIN"
echo "   API:      https://$API_DOMAIN/v1"
echo "   Tracking: https://$TRACKING_DOMAIN"
echo "   Next: publish the DNS records the seed printed for the platform domain, then"
echo "   sign in to the console with the owner login it printed and change the password."
echo "=============================================================================="
