#!/usr/bin/env bash
# ==============================================================================
# TredMail Automated Production Deployment Script for Hostinger KVM VPS
# A Product of Dovepeak Technology
# ==============================================================================

set -e

echo "🚀 Starting TredMail Production Deployment on Hostinger KVM..."

# 1. Update OS packages
echo "📦 Updating Ubuntu package repositories..."
sudo apt-get update -y && sudo apt-get upgrade -y
sudo apt-get install -y curl git ufw jq dnsutils

# 2. Install Docker & Docker Compose if not present
if ! command -v docker &> /dev/null; then
    echo "🐳 Installing Docker Engine..."
    curl -fsSL https://get.docker.com -o get-docker.sh
    sudo sh get-docker.sh
    sudo usermod -aG docker $USER
    rm get-docker.sh
fi

if ! docker compose version &> /dev/null; then
    echo "🐳 Installing Docker Compose Plugin..."
    sudo apt-get install -y docker-compose-plugin
fi

# 3. Deliverability Diagnostic: Check Reverse DNS (PTR)
SERVER_IP=$(curl -s -4 https://ifconfig.me || hostname -I | awk '{print $1}')
echo "🔍 Checking Reverse DNS for IP: $SERVER_IP..."
PTR_RECORD=$(dig -x $SERVER_IP +short || true)

EXPECTED_PTR="${MTA_HOSTNAME:-mta1.tredmail.dovepeakdigital.com}"
if [ -z "$PTR_RECORD" ]; then
    echo "⚠️ WARNING: No PTR (Reverse DNS) record detected for $SERVER_IP."
    echo "   Action needed: hPanel -> VPS -> Settings -> PTR record, set to $EXPECTED_PTR (or ask Hostinger support)"
elif [ "${PTR_RECORD%.}" != "$EXPECTED_PTR" ]; then
    echo "⚠️ WARNING: PTR for $SERVER_IP is $PTR_RECORD but must be $EXPECTED_PTR (it must match the HELO name)."
else
    echo "✅ Reverse DNS matches: $PTR_RECORD"
fi

# Inbound port 25 receives bounces and complaints; open it if the host firewall is active.
if command -v ufw &> /dev/null && sudo ufw status | grep -q "Status: active"; then
    sudo ufw allow 25/tcp > /dev/null && echo "✅ Firewall allows inbound port 25"
    # SMTP relay for applications (587 STARTTLS, 465 TLS)
    sudo ufw allow 587/tcp > /dev/null && sudo ufw allow 465/tcp > /dev/null && echo "✅ Firewall allows the SMTP relay ports 587 and 465"
fi
if ss -ltn 2>/dev/null | grep -qE '(0\.0\.0\.0|\[::\]|\*):25 ' && ! docker ps --format '{{.Names}}' | grep -q kumomta; then
    echo "⚠️ WARNING: another mail server (Postfix/Exim) is listening on port 25; stop it so KumoMTA can bind the port."
fi

# 4. Deliverability Diagnostic: Check Outbound Port 25
echo "🔍 Checking Outbound Port 25 Connectivity..."
if timeout 5 bash -c '</dev/tcp/gmail-smtp-in.l.google.com/25' 2>/dev/null; then
    echo "✅ Port 25 Outbound is OPEN and reachable."
else
    echo "⚠️ NOTICE: Outbound Port 25 connection timed out."
    echo "   If blocked, contact Hostinger support to unblock port 25 for your business transactional emails."
fi

# 5. Environment file. STAGE=staging deploys a staging stack whose outbound mail is captured
#    by Mailpit instead of delivered.
STAGE="${STAGE:-production}"
ENV_FILE=".env"
[ "$STAGE" = "staging" ] && ENV_FILE=".env.staging"
COMPOSE=(docker compose -f docker-compose.prod.yml --env-file "$ENV_FILE" -p "tredmail-$STAGE")
if [ "$STAGE" = "staging" ]; then
    COMPOSE+=(--profile staging-relay)
    # Real delivery to allowlisted team addresses, when configured in .env.staging
    if [ -f "$ENV_FILE" ] && grep -qE '^STAGING_DELIVERY_ALLOWLIST=.+' "$ENV_FILE"; then
        COMPOSE+=(--profile staging-delivery)
    fi
else
    COMPOSE+=(--profile mta) # KumoMTA on port 25 and the SMTP relay on 587/465
fi

if [ ! -f "$ENV_FILE" ]; then
    : "${CONSOLE_DOMAIN:?Set CONSOLE_DOMAIN, API_DOMAIN and TRACKING_DOMAIN before the first deploy}"
    : "${API_DOMAIN:?Set API_DOMAIN}"
    : "${TRACKING_DOMAIN:?Set TRACKING_DOMAIN}"
    echo "📝 Generating $ENV_FILE with fresh secrets..."
    umask 077
    {
        echo "# Generated by deploy-hostinger.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Back this file up securely:"
        echo "# losing TREDMAIL_MASTER_ENCRYPTION_KEY makes every stored DKIM key unrecoverable."
        echo "CONSOLE_DOMAIN=$CONSOLE_DOMAIN"
        echo "API_DOMAIN=$API_DOMAIN"
        echo "TRACKING_DOMAIN=$TRACKING_DOMAIN"
        echo "PRIMARY_DOMAIN=${PRIMARY_DOMAIN:-tredmail.dovepeakdigital.com}"
        echo "TREDMAIL_MASTER_ENCRYPTION_KEY=$(openssl rand -hex 32)"
        echo "INTERNAL_API_TOKEN=$(openssl rand -hex 32)"
        echo "BETTER_AUTH_SECRET=$(openssl rand -hex 32)"
        echo "POSTGRES_PASSWORD=$(openssl rand -hex 24)"
        if [ "$STAGE" = "staging" ]; then
            echo "SMTP_HOST=mailpit"
            echo "SMTP_PORT=1025"
            echo "# Optional: deliver mail for these addresses/@domains for real (comma separated)"
            echo "STAGING_DELIVERY_ALLOWLIST="
            echo "STAGING_DELIVERY_SMTP_HOST=kumomta-staging"
        else
            echo "# The worker hands mail to KumoMTA inside the Docker network"
            echo "SMTP_HOST=kumomta"
            echo "SMTP_PORT=2525"
            echo "MTA_HOSTNAME=${MTA_HOSTNAME:-mta1.tredmail.dovepeakdigital.com}"
            echo "# Alerts and mail sent to postmaster@/abuse@/dmarc@ are forwarded here"
            echo "OPS_EMAIL=${OPS_EMAIL:-}"
            echo "# IP warm-up starts today; clear this line after day 20"
            echo "MTA_WARMUP_START=${MTA_WARMUP_START:-$(date -u +%Y-%m-%d)}"
            echo "# Optional backup provider for mail above the warm-up cap"
            echo "FALLBACK_SMTP_HOST="
            echo "FALLBACK_SMTP_PORT=587"
            echo "FALLBACK_SMTP_USER="
            echo "FALLBACK_SMTP_PASS="
            echo "# SMTP relay hostname (its A record must point here) and MTA-STS mode (testing, then enforce)"
            echo "SMTP_RELAY_HOSTNAME=${SMTP_RELAY_HOSTNAME:-smtp.tredmail.dovepeakdigital.com}"
            echo "MTA_STS_MODE=testing"
        fi
    } > "$ENV_FILE"
    echo "🔑 Generated encryption key, internal token, session secret and database password."
fi

# 6. Build images, start the database, apply migrations, then start everything
echo "🚢 Building and starting TredMail ($STAGE)..."
"${COMPOSE[@]}" build
"${COMPOSE[@]}" up -d postgres redis
echo "🗄️ Applying database migrations..."
"${COMPOSE[@]}" run --rm --no-deps api npx prisma migrate deploy --schema=packages/db/prisma/schema.prisma
"${COMPOSE[@]}" up -d

# 7. Production: copy Caddy's certificates to KumoMTA and the SMTP relay now and twice a day.
#    Caddy may need a minute to obtain them on the first deploy; the cron job catches up.
if [ "$STAGE" = "production" ]; then
    chmod +x scripts/cert-sync.sh
    sleep 20
    ./scripts/cert-sync.sh "tredmail-$STAGE" || true
    echo "17 3,15 * * * root cd $(pwd) && ./scripts/cert-sync.sh tredmail-$STAGE >> /var/log/tredmail-cert-sync.log 2>&1" | sudo tee /etc/cron.d/tredmail-cert-sync > /dev/null
    echo "🔐 Certificate sync scheduled (/etc/cron.d/tredmail-cert-sync)"
fi

# 8. Seed the platform and Dovepeak workspaces (prints an owner password and an API key once)
echo "🌱 Seeding workspaces..."
"${COMPOSE[@]}" run --rm --no-deps api node apps/api/dist/cli/seed.js

# 9. Register payment notification URLs with M-Pesa (production only; Safaricom keeps the
#    first registration, so a failure here is reported but does not stop the deploy)
if [ "$STAGE" = "production" ] && grep -qE '^MPESA_CONSUMER_KEY=.+' "$ENV_FILE"; then
  echo "💳 Registering M-Pesa notification URLs..."
  "${COMPOSE[@]}" run --rm --no-deps api node apps/api/dist/cli/payments-setup.js || echo "⚠️  M-Pesa URL registration failed; run it again later (see docs/BILLING_AND_PAYMENTS.md)"
fi

# shellcheck disable=SC1090
source <(grep -E '^(CONSOLE|API|TRACKING)_DOMAIN=' "$ENV_FILE")
echo ""
echo "=============================================================================="
echo "🎉 TredMail ($STAGE) is up"
echo "   Console:  https://$CONSOLE_DOMAIN"
echo "   API:      https://$API_DOMAIN/v1"
echo "   Tracking: https://$TRACKING_DOMAIN"
echo "   Next: publish the DNS records the seed printed for the platform domain, then"
echo "   sign in to the console with the owner login it printed and change the password."
echo "=============================================================================="
